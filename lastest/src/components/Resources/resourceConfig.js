const relation = (key, label, resource, optionLabel, required = false) => ({
  kind: 'relation',
  key,
  label,
  resource,
  optionLabel,
  required,
})
const text = (label, required = false, extra = {}) => ({
  label,
  required,
  nullable: !required,
  ...extra,
})
const number = (label, required = false, extra = {}) =>
  text(label, required, {
    type: 'number',
    step: '0.01',
    min: '0',
    nullable: false,
    ...extra,
  })
const date = (label, required = false, includeTime = false) =>
  text(label, required, {
    type: includeTime ? 'datetime-local' : 'date',
    defaultNow: required,
    nullable: !required,
  })
const select = (label, options, required = false, extra = {}) =>
  text(label, required, { type: 'select', options, ...extra })
const checkbox = (label, defaultValue = false) =>
  text(label, false, { type: 'checkbox', defaultValue, nullable: false })

